def to_html(comparison: Comparison) -> str:
    """Stand-alone, escaped report. No scripts, fonts, CDN, or network calls."""
    payload = to_payload(comparison)
    categories = (
        ("regressions", "Introduced regressions"),
        ("new_failures", "New failing tests"),
        ("existing_failures", "Pre-existing failures"),
        ("fixed", "Fixed failures"),
        ("flaky", "Unstable / incomplete tests"),
        ("added", "Added tests"),
        ("removed", "Removed tests"),
        ("other", "Other observations"),
    )
    lines = [
        "<!doctype html>", '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        '<meta name="referrer" content="no-referrer">',
        "<meta http-equiv=\"Content-Security-Policy\" "
        "content=\"default-src 'none'; style-src 'unsafe-inline'; img-src 'none'; "
        "connect-src 'none'; form-action 'none'; base-uri 'none'\">",
        "<title>RegressionProof — Test comparison</title>",
        f"<style>{_HTML_CSS}</style></head><body><main>",
        '<div class="muted">RegressionProof / Test comparison</div>',
        "<h1>Revision comparison</h1>",
        f'<span class="status {payload["status"]}">'
        f'{html_escape(payload["status"].replace("_", " "))}</span>',
        '<p class="subtitle">Evidence from actual JUnit test runs. '
        'Not a causality or security proof.</p>', 
        '<div class="meta">',
        f'<div><strong>Base:</strong> <code>{html_escape(comparison.base.ref)}</code> '
        f'(<code>{html_escape(comparison.base.sha[:12])}</code>)</div>',
        f'<div><strong>Head:</strong> <code>{html_escape(comparison.head.ref)}</code> '
        f'(<code>{html_escape(comparison.head.sha[:12])}</code>)</div>',
        f'<div class="muted">Runs: {len(comparison.base.runs)} baseline / '
        f'{len(comparison.head.runs)} candidate</div></div>',
        '<div class="summary">',
    ]
    for category, title in categories[:5]:
        lines.append(f'<div class="tile"><div class="value">{payload["counts"][category]}</div>'
                     f'<div class="label">{html_escape(title)}</div></div>')
    lines.append('</div>')
    for category, title in categories:
        items = getattr(comparison, category)
        lines.append('<section><details' + (' open' if items else '') + '><summary>' +
                     html_escape(title) +
                     f'<span class="summary-count">{len(items)}</span></summary>')
        if not items:
            lines.append('<small>No observations.</small>')
        else:
            lines.append('<div class="table-wrap"><table><thead><tr><th scope="col">Test</th>'
                         '<th scope="col">Base</th><th scope="col">Head</th></tr></thead><tbody>')
            for item in items[:1000]:
                lines.append('<tr><td><code>' + html_escape(item.key) + '</code></td><td>' +
                             html_escape(item.base) + '</td><td>' + html_escape(item.head) +
                             '</td></tr>')
            lines.append('</tbody></table></div>')
            if len(items) > 1000:
                lines.append(f'<small>{len(items) - 1000} additional entries '
                             'in result.json.</small>')
        lines.append('</details></section>')
    lines.append('<footer>RegressionProof 0.2.0. Test names originate from JUnit XML. '
                 'Missing tests are not considered passing.</footer></main></body></html>')
    return "\n".join(lines) + "\n"

def write_report(comparison: Comparison, directory: Path) -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    json_path = directory / "result.json"
    markdown_path = directory / "report.md"
    html_path = directory / "report.html"
    json_path.write_text(json.dumps(to_payload(comparison), indent=2, ensure_ascii=False) + "\n",
                         encoding="utf-8")
    markdown_path.write_text(to_markdown(comparison), encoding="utf-8")
    html_path.write_text(to_html(comparison), encoding="utf-8")
    return json_path, markdown_path
