"""Portable JSON output and an intentionally small Markdown report."""

from __future__ import annotations

import json
from html import escape as html_escape
from datetime import datetime, timezone
from pathlib import Path

from .model import Comparison


def to_payload(comparison: Comparison) -> dict:
    groups = (
        "regressions", "new_failures", "existing_failures", "fixed", "flaky",
        "added", "removed", "other"
    )
    return {
        "schema_version": 1,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "tool": "regressionproof",
        "base": {"ref": comparison.base.ref, "sha": comparison.base.sha,
                 "runs": len(comparison.base.runs)},
        "head": {"ref": comparison.head.ref, "sha": comparison.head.sha,
                 "runs": len(comparison.head.runs)},
        "status": "regression" if comparison.has_new_failure else (
            "unstable" if comparison.flaky else "no_new_failures"
        ),
        "counts": {name: len(getattr(comparison, name)) for name in groups},
        "tests": {
            name: [vars(item) for item in getattr(comparison, name)] for name in groups
        },
    }


def _escaped(value: str) -> str:
    return (value.replace("\\", "\\\\")
            .replace("|", "\\|").replace("`", "\\`")
            .replace("\r", " ").replace("\n", " "))


def to_markdown(comparison: Comparison) -> str:
    payload = to_payload(comparison)
    sections = [
        ("Introduced regressions", comparison.regressions),
        ("New tests failing", comparison.new_failures),
        ("Pre-existing failures", comparison.existing_failures),
        ("Fixed failures", comparison.fixed),
        ("Unstable / incomplete tests", comparison.flaky),
        ("Added tests", comparison.added),
        ("Removed tests", comparison.removed),
    ]
    lines = [
        "# RegressionProof test comparison", "",
        f"**Result:** `{payload['status']}`", "",
        f"- Base: `{_escaped(comparison.base.ref)}` (`{comparison.base.sha[:12]}`)",
        f"- Head: `{_escaped(comparison.head.ref)}` (`{comparison.head.sha[:12]}`)",
        f"- Runs per revision: {len(comparison.base.runs)} / {len(comparison.head.runs)}",
        "", "A failing test is a regression only when it passed consistently on the base.", "",
    ]
    for title, tests in sections:
        lines.extend([f"## {title} ({len(tests)})", ""])
        if tests:
            lines.extend(["| Test | Base | Head |", "| --- | --- | --- |"])
            for test in tests[:100]:
                lines.append(
                    f"| `{_escaped(test.key)}` | {test.base} | {test.head} |"
                )
            if len(tests) > 100:
                lines.append(f"\n{len(tests) - 100} additional entries in result.json")
        else:
            lines.append("None.")
        lines.append("")
    lines.extend([
        "---", "", "**Limitations:** This comparison does not identify the causal commit,",
        "prove that a change is safe, or sandbox the test process. A missing test is not a pass.",
        "", "Generated by RegressionProof 0.2.0.", "",
    ])
    return "\n".join(lines)



